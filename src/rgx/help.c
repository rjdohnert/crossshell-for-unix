#include "help.h"

void print_help(void) {
    printf("rgx %s\n", RGX_VERSION);
    printf("Fast, object-oriented Windows recursive regex pattern searcher.\n\n");
    printf("USAGE:\n");
    printf("    rgx [OPTIONS] <PATTERN> [PATH ...]\n");
    printf("    rgx [OPTIONS] -e <PATTERN> ... [PATH ...]\n\n");
    printf("ARGS:\n");
    printf("    <PATTERN>                 A regular expression (or literal with -F) to search for.\n");
    printf("    <PATH>...                 A file or directory to search. [default: .]\n\n");
    printf("OPTIONS:\n");
    printf("  MATCH QUALIFIERS:\n");
    printf("    -e, --regexp <PAT>        A pattern to search for. Can be provided multiple times.\n");
    printf("    -F, --fixed-strings       Treat PATTERN as a literal string instead of regex.\n");
    printf("    -i, --ignore-case         Case insensitive search.\n");
    printf("    -s, --case-sensitive      Search case-sensitively; last case option wins.\n");
    printf("    -S, --smart-case          Search case-insensitively if pattern is all lowercase.\n");
    printf("    -v, --invert-match        Invert match: select non-matching lines.\n");
    printf("    -w, --word-regexp         Only show matches surrounded by word boundaries.\n");
    printf("    -x, --line-regexp         Match the entire line.\n");
    printf("    -f, --file <FILE>         Read patterns from FILE (or '-' for stdin).\n\n");
    printf("    -U, --multiline           Allow cross-line matches; bounded to 64 MiB.\n");
    printf("        --multiline-dotall    Enable multiline and newline-matching dots.\n\n");
    printf("  OUTPUT QUALIFIERS:\n");
    printf("    -c, --count               Show only the count of matching lines per file.\n");
    printf("        --color <WHEN>        When to use color: 'never', 'auto', 'always'. [default: auto]\n");
    printf("    -l, --files-with-matches  Print only the paths with at least one match.\n");
    printf("        --files-without-match Print only the paths that contain zero matches.\n");
    printf("    -n, --line-number         Show line numbers (1-based); automatic on a console.\n");
    printf("    -N, --no-line-number      Suppress line numbers.\n");
    printf("    -o, --only-matching       Print only the matched parts of a matching line.\n");
    printf("    -q, --quiet               Do not print matches; exit immediately when match is found.\n\n");
    printf("    -H, --with-filename       Always print the path.\n");
    printf("    -I, --no-filename         Never print the path.\n");
    printf("        --count-matches       Count individual matches instead of lines.\n");
    printf("    -a, --text                Search files containing NUL bytes as text.\n");
    printf("        --crlf                Treat CRLF as a line terminator.\n\n");
    printf("        --json                Emit begin/match/context/end/summary JSON events.\n");
    printf("    -b, --byte-offset         Show decoded-input byte offsets.\n");
    printf("        --column              Show one-based byte columns.\n");
    printf("    -r, --replace <TEXT>      Replace matches; $0 inserts the match, $$ inserts '$'.\n");
    printf("    -0, --null                NUL-delimit filenames.\n");
    printf("        --heading             Group output under filenames.\n");
    printf("        --no-heading          Use filename prefixes.\n");
    printf("        --stats               Report search counters and elapsed time.\n\n");
    printf("  CONTEXT QUALIFIERS:\n");
    printf("    -A, --after-context <NUM> Show <NUM> lines after each match.\n");
    printf("    -B, --before-context <NUM>Show <NUM> lines before each match.\n");
    printf("    -C, --context <NUM>       Show <NUM> lines before and after each match.\n");
    printf("    -m, --max-count <NUM>     Limit the number of matching lines per file.\n\n");
    printf("  DIRECTORY TRAVERSAL:\n");
    printf("        --hidden              Search hidden files and folders.\n");
    printf("        --max-depth <NUM>     Descend at most <NUM> directories deep.\n");
    printf("        --no-ignore           Ignore local .gitignore, .ignore and .rgignore rules.\n");
    printf("    -g, --glob <GLOB>         Include matching paths; prefix '!' to exclude.\n");
    printf("        --files               List searchable files without a pattern.\n\n");
    printf("        --no-require-git      Apply Git ignores outside repositories too.\n");
    printf("    -t, --type <NAME>         Include a builtin/custom file type.\n");
    printf("    -T, --type-not <NAME>     Exclude a file type.\n");
    printf("        --type-list           List file types.\n");
    printf("        --type-add NAME:GLOB  Add a custom type pattern.\n");
    printf("        --type-clear NAME     Remove builtin patterns.\n");
    printf("    -j, --threads <N>         Up to 16 Windows workers; 0 is automatic (default).\n\n");
    printf("  INFO:\n");
    printf("    -h, --help                Prints help information.\n");
    printf("    -V, --version             Prints version information.\n");
    printf("\nRegex: groups, alternatives, classes, greedy/lazy repetitions, anchors,\n");
    printf("word boundaries, character escapes and inline i/m/s flags.\n");
    printf("Properties: L, Lu, Ll, Nd, M, P, ASCII, Word, White_Space,\n");
    printf("Greek, Latin, Cyrillic and Han (Windows classifications/block ranges).\n");
    printf("Backreferences, look-around and capture replacements are unsupported.\n");
    printf("Native Windows C implementation; not full ripgrep compatibility.\n");
    printf("Limits: 64 MiB per line/context text; 16 MiB option/ignore/queue budgets;\n");
    printf("8192 states per regex, 32768 aggregate states; bounded search work.\n");
    printf("Combined literals: 1 MiB; worker output: 64 MiB per file.\n");
    printf("Multiline inversion is unsupported; multiline replacement requires -o.\n");
    printf("Exit codes: 0 selected matches, 1 no selected matches, 2 errors.\n");
}
