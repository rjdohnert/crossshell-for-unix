#include "help.h"

void Yum_ShowHelp(void) {
    wprintf(
        L"Loaded plugins: fastestmirror, native-wua, native-rpm\n"
        L"Usage: yum [options] COMMAND [package ...]\n\n"
        L"Yellowdog Updater, Modified (YUM) " YUM_VERSION L"\n"
        L"Main Commands:\n"
        L"  install <pkg ...>           Install package(s) or local .rpm package files\n"
        L"  localinstall <file.rpm ...> Install local RPM package files using native rpm engine\n"
        L"  localupdate <file.rpm ...>  Update local RPM package files using native rpm engine\n"
        L"  reinstall <pkg ...>         Reinstall package(s)\n"
        L"  downgrade <pkg ...>         Downgrade package(s)\n"
        L"  remove | erase <pkg ...>    Remove package(s) from the system\n"
        L"  update                      Query Windows Update Agent via native COM\n"
        L"  check-update                Check for available winget and Windows updates\n"
        L"  upgrade [pkg ...]           Upgrade specific package(s) or all managed packages\n"
        L"  clean [all|metadata|cache]  Clean repository cache and downloaded packages\n"
        L"  sys-upgrade                 Download/install pending Windows software updates\n"
        L"  search <keyword ...>        Search repository package names/summaries\n"
        L"  info <pkg ...>              Display package metadata or inspect .rpm file\n"
        L"  list [all|installed|updates] List packages installed or available for upgrade\n"
        L"  repolist                    Display active package repositories\n"
        L"  repo add <name> <url>       Register a new package repository/feed\n"
        L"  repo remove <name>          Unregister a package repository\n"
        L"  help                        Show this menu\n\n"
        L"Options:\n"
        L"  -y, --assumeyes             Answer yes to all confirmations\n"
        L"  -v, --verbose               Log detailed execution statements\n"
        L"  -q, --quiet                 Quiet operation\n"
        L"  -h, --help                  Display this comprehensive reference and exit\n"
        L"  --version                   Display version and exit\n\n"
        L"Package Formats:\n"
        L"  RPM: Files ending in .rpm are automatically dispatched to the native CrossShell\n"
        L"       rpm engine (rpm.exe). Installed RPM packages can also be removed or queried.\n"
        L"  Windows Package Manager: Standard packages are managed via winget.\n\n"
        L"Windows Updates:\n"
        L"  update lists pending updates; sys-upgrade installs non-hidden software updates.\n"
        L"  sys-upgrade requires an Administrator terminal and confirms installation/licenses.\n"
        L"  Use -y to skip confirmation; Windows Update service policy is respected.\n"
        L"  No automatic reboot. Exit 3010 means a restart is required; 1 means failure.\n"
    );
}
